/**
 * dynamicColor defaults to false: we use our own deliberately designed palette
 * (see Color.kt) rather than Android 12+'s wallpaper-derived Material You
 * colors, which look inconsistent and often muted depending on the user's
 * wallpaper. Pass dynamicColor = true if wallpaper-matching is ever wanted.
 */
@Composable
fun NsaTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    classicStyle: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }

    // The whole app is Persian, so the layout is always right-to-left — even on a phone whose
    // system language is English. Without this, tabs, back arrows, swipe directions and list
    // alignment would flip depending on the phone's locale.
    CompositionLocalProvider(
        LocalLayoutDirection provides LayoutDirection.Rtl,
        LocalClassicStyle provides classicStyle
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            shapes = NsaShapes,
            content = content
        )
    }
}
