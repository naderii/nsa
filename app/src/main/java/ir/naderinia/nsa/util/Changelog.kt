    fun since(lastSeenVersionCode: Int): List<ChangelogEntry> =
        entries
            .filter { it.versionCode > lastSeenVersionCode }
            .sortedByDescending { it.versionCode }

    val latest: ChangelogEntry
        get() = entries.maxByOrNull { it.versionCode }!!
}

